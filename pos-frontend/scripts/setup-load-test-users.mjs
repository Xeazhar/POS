/**
 * Provisions the staff accounts the 28/50/100/200-user load tests log in as:
 * 7 branches × (1 supervisor + 3 cashiers) = 28 accounts.
 *
 *   npm run setup:load-test
 *
 * Idempotent — safe to re-run. Existing branches/staff are reused as-is (PINs are not
 * rotated), so re-running after a partial failure or to top up a new branch is normal use.
 *
 * Uses the Supabase service role key, so this must NEVER run against calepos-dev,
 * calepos-staging, or production — only a dedicated load-test project. Reads connection
 * details from `.env.test` (gitignored; copy from `.env.test.example`), which the script
 * refuses to proceed without, plus an explicit confirmation literal so a stray copy-paste
 * can't silently point this at the wrong project.
 *
 * Mirrors createStaffAccount()'s auth-email/staff-row shape (src/lib/api.js) but goes
 * through supabase.auth.admin.createUser() instead of auth.signUp() — that's an
 * admin-privileged call, so it bypasses the Turnstile captcha check entirely (no site key
 * needed to run this script). The load-test *traffic* itself (the actual sign-ins during a
 * stress run) still goes through the normal login flow and does need a Turnstile site key —
 * see .env.test.example for Cloudflare's official test key pair.
 */
import { createClient } from '@supabase/supabase-js'
import { randomInt } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { pinAuthEmail } from '../src/utils/roles.js'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const ENV_PATH = join(root, '.env.test')

const CONFIRM_LITERAL = 'i-understand-this-is-not-production'
const BRANCH_COUNT = 7
const CASHIERS_PER_BRANCH = 3
const CASHIER_LETTERS = ['A', 'B', 'C']

const CRED_START = '# --- LOAD_TEST_CREDENTIALS (generated by `npm run setup:load-test` — do not hand-edit) ---'
const CRED_END = '# --- END LOAD_TEST_CREDENTIALS ---'

function pad2(n) {
  return String(n).padStart(2, '0')
}

function randomPin(length = 6) {
  let out = ''
  for (let i = 0; i < length; i += 1) out += String(randomInt(0, 10))
  return out
}

function supervisorCode(branchIndex) {
  return `90${pad2(branchIndex)}`
}

function cashierCode(branchIndex, cashierIndex) {
  return `${pad2(branchIndex)}${pad2(cashierIndex)}`
}

function parseEnvFile(text) {
  const vars = {}
  for (const line of text.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eq = trimmed.indexOf('=')
    if (eq === -1) continue
    const key = trimmed.slice(0, eq).trim()
    let value = trimmed.slice(eq + 1).trim()
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1)
    }
    vars[key] = value
  }
  return vars
}

function loadEnvTest() {
  if (!existsSync(ENV_PATH)) {
    throw new Error(
      `Missing pos-frontend/.env.test. Copy .env.test.example to .env.test and fill in your ` +
        `dedicated load-test Supabase project's URL + service role key, then re-run.`,
    )
  }
  const raw = readFileSync(ENV_PATH, 'utf-8')
  return { raw, vars: parseEnvFile(raw) }
}

function requireConfig(vars) {
  const missing = ['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY'].filter((k) => !vars[k])
  if (missing.length) {
    throw new Error(`.env.test is missing: ${missing.join(', ')}. See .env.test.example.`)
  }
  if (vars.SUPABASE_TEST_CONFIRM !== CONFIRM_LITERAL) {
    throw new Error(
      `.env.test must set SUPABASE_TEST_CONFIRM=${CONFIRM_LITERAL} — this is a deliberate ` +
        `tripwire so this script can't run against the wrong project by accident.`,
    )
  }
}

async function ensureBranch(supabase, name) {
  const { data: existing, error: selectError } = await supabase
    .from('branches')
    .select('id')
    .eq('name', name)
    .maybeSingle()
  if (selectError) throw selectError
  if (existing) return existing.id

  const { data: inserted, error: insertError } = await supabase
    .from('branches')
    .insert({ name, branch_type: 'retail', is_active: true })
    .select('id')
    .maybeSingle()
  if (insertError) throw insertError
  return inserted.id
}

/** Looks up an existing auth user by email — only hit on the rare create/insert race below. */
async function findAuthUserByEmail(supabase, email) {
  const { data, error } = await supabase.auth.admin.listUsers({ page: 1, perPage: 1000 })
  if (error) throw error
  return data.users.find((u) => u.email === email) || null
}

async function ensureAccount(supabase, { branchId, branchName, role, loginCode, fullName }) {
  const { data: existingStaff, error: selectError } = await supabase
    .from('staff')
    .select('id, login_pin')
    .eq('login_code', loginCode)
    .maybeSingle()
  if (selectError) throw selectError
  if (existingStaff) {
    return { branchName, role, fullName, loginCode, pin: existingStaff.login_pin, created: false }
  }

  const pin = randomPin()
  const authEmail = pinAuthEmail(loginCode, branchId)

  const { data: created, error: createError } = await supabase.auth.admin.createUser({
    email: authEmail,
    password: pin,
    email_confirm: true,
    user_metadata: { full_name: fullName, role, branch_id: branchId },
  })

  let authUserId = created?.user?.id
  if (createError) {
    if (!/already.*registered|already.*exist/i.test(createError.message || '')) throw createError
    const existingUser = await findAuthUserByEmail(supabase, authEmail)
    if (!existingUser) throw createError
    authUserId = existingUser.id
  }

  const staffPayload = {
    auth_user_id: authUserId,
    branch_id: branchId,
    full_name: fullName,
    role,
    is_active: true,
    login_code: loginCode,
    login_pin: pin,
    auth_secret: pin,
    permissions: null,
  }
  const { data: inserted, error: insertError } = await supabase
    .from('staff')
    .insert(staffPayload)
    .select('id')
    .maybeSingle()
  if (insertError) {
    // 23505: a trigger (handle_new_user) or a concurrent run already created the row for
    // this auth user — apply the payload to it instead of leaving it PIN-less.
    if (insertError.code === '23505') {
      const { data: found } = await supabase
        .from('staff')
        .select('id')
        .eq('auth_user_id', authUserId)
        .maybeSingle()
      if (found?.id) {
        const { error: updateError } = await supabase.from('staff').update(staffPayload).eq('id', found.id)
        if (updateError) throw updateError
        return { branchName, role, fullName, loginCode, pin, created: true }
      }
    }
    throw insertError
  }
  void inserted
  return { branchName, role, fullName, loginCode, pin, created: true }
}

function buildCredentialsBlock(results) {
  const lines = [CRED_START]
  for (const r of results) {
    const prefix = `LOADTEST_${r.branchKey}_${r.role.toUpperCase()}${r.suffix ? `_${r.suffix}` : ''}`
    lines.push(`${prefix}_CODE=${r.loginCode}`)
    lines.push(`${prefix}_PIN=${r.pin}`)
  }
  lines.push(CRED_END)
  return `${lines.join('\n')}\n`
}

function writeCredentials(raw, block) {
  const re = new RegExp(
    `${CRED_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${CRED_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\n?`,
  )
  const next = re.test(raw) ? raw.replace(re, block) : `${raw.replace(/\n+$/, '\n')}\n${block}`
  writeFileSync(ENV_PATH, next)
}

async function main() {
  const { raw, vars } = loadEnvTest()
  requireConfig(vars)

  console.log(`Provisioning load-test users against: ${vars.SUPABASE_URL}`)
  console.log('(Ctrl+C now if that is not your dedicated load-test project.)\n')

  const supabase = createClient(vars.SUPABASE_URL, vars.SUPABASE_SERVICE_ROLE_KEY, {
    auth: { autoRefreshToken: false, persistSession: false },
  })

  const results = []
  let created = 0
  let reused = 0

  for (let i = 1; i <= BRANCH_COUNT; i += 1) {
    const branchKey = `BRANCH_${pad2(i)}`
    const branchName = `Load Test Branch ${pad2(i)}`
    const branchId = await ensureBranch(supabase, branchName)

    const supervisor = await ensureAccount(supabase, {
      branchId,
      branchName,
      role: 'supervisor',
      loginCode: supervisorCode(i),
      fullName: `Load Test Supervisor ${i}`,
    })
    results.push({ ...supervisor, branchKey })
    supervisor.created ? (created += 1) : (reused += 1)

    for (let c = 1; c <= CASHIERS_PER_BRANCH; c += 1) {
      const letter = CASHIER_LETTERS[c - 1]
      const cashier = await ensureAccount(supabase, {
        branchId,
        branchName,
        role: 'cashier',
        loginCode: cashierCode(i, c),
        fullName: `Load Test Cashier ${i}${letter}`,
      })
      results.push({ ...cashier, branchKey, suffix: letter })
      cashier.created ? (created += 1) : (reused += 1)
    }

    console.log(`✓ ${branchName} — supervisor ${supervisorCode(i)}, cashiers ${cashierCode(i, 1)}/${cashierCode(i, 2)}/${cashierCode(i, 3)}`)
  }

  writeCredentials(raw, buildCredentialsBlock(results))

  console.log(`\n${results.length} accounts ready (${created} created, ${reused} already existed).`)
  console.log('Login codes + PINs written to pos-frontend/.env.test — do not commit that file.')
}

main().catch((error) => {
  console.error(`\nsetup:load-test failed: ${error.message}`)
  process.exitCode = 1
})
